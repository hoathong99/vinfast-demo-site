import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

/*
 * Build idempotent D1 seed SQL from the static catalog + article seed.
 *
 * Run: npm run seed:build
 * Output: backend/seed/01-sale-items.sql ... 04-articles.sql
 */

const projectRoot = fileURLToPath(new URL("..", import.meta.url));
const catalogDir = join(projectRoot, "src", "data", "catalog");
const outputDir = join(projectRoot, "backend", "seed");
const seededAt = "2026-11-26T00:00:00.000Z";

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function sqlValue(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    return Number.isFinite(value) ? String(value) : "0";
  }
  if (typeof value === "boolean") return value ? "1" : "0";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlList(values) {
  return values.map(sqlValue).join(", ");
}

function header(title) {
  return [
    `-- ${title}`,
    "-- Generated by scripts/build-d1-seed.mjs. Do not edit by hand.",
    `-- Generated at: ${new Date().toISOString()}`,
    "",
  ].join("\n");
}

function writeSql(filename, title, statements) {
  const body = `${header(title)}${statements.join("\n")}\n`;
  writeFileSync(join(outputDir, filename), body, "utf8");
  const kb = (Buffer.byteLength(body, "utf8") / 1024).toFixed(1);
  console.log(`  ${filename}  ${statements.length} statements, ${kb} KB`);
}

const productsFile = readJson(join(catalogDir, "products.json"));
const saleItemsFile = readJson(join(catalogDir, "sale-items.json"));
const saleProgramsFile = readJson(join(catalogDir, "sale-programs.json"));
const articlesFile = readJson(join(outputDir, "articles.json"));

const products = productsFile.products || [];
const saleItems = saleItemsFile.items || [];
const salePrograms = saleProgramsFile.programs || [];
const articles = articlesFile.articles || [];

mkdirSync(outputDir, { recursive: true });

console.log("Building D1 seed SQL...");

/* ------------------------------------------------------------------ */
/* Sale items                                                          */
/* ------------------------------------------------------------------ */

const saleItemStatements = [];

saleItems.forEach((item, index) => {
  saleItemStatements.push(
    `INSERT INTO sale_items (id, name, sort_order, created_at, updated_at)
VALUES (${sqlList([item.id, item.name, index, seededAt, seededAt])})
ON CONFLICT(id) DO UPDATE SET
  name = excluded.name,
  sort_order = excluded.sort_order,
  updated_at = excluded.updated_at;`,
  );
});

writeSql(
  "01-sale-items.sql",
  `Sale items (${saleItems.length})`,
  saleItemStatements,
);

/* ------------------------------------------------------------------ */
/* Products                                                            */
/* ------------------------------------------------------------------ */

const productStatements = [];

products.forEach((product, index) => {
  const slug = product.slug;
  const quickSpecs = Array.isArray(product.quickSpecs) ? product.quickSpecs : [];
  const specs = Array.isArray(product.specs) ? product.specs : [];
  const images = Array.isArray(product.images) ? product.images : [];
  const colors = Array.isArray(product.colors) ? product.colors : [];
  const offers = Array.isArray(product.offers) ? product.offers : [];
  const highlights = Array.isArray(product.highlights) ? product.highlights : [];

  productStatements.push(
    `INSERT INTO products (
  slug, name, type, category, tagline, price, price_note, badge,
  featured, sort_order, description, status, created_at, updated_at
) VALUES (${sqlList([
      slug,
      product.name,
      product.type,
      product.category,
      product.tagline || "",
      Number(product.price) || 0,
      product.priceNote || "",
      product.badge || "",
      product.featured ? 1 : 0,
      Number.isFinite(Number(product.order)) ? Number(product.order) : index,
      product.description || "",
      product.status || "published",
      seededAt,
      seededAt,
    ])})
ON CONFLICT(slug) DO UPDATE SET
  name = excluded.name,
  type = excluded.type,
  category = excluded.category,
  tagline = excluded.tagline,
  price = excluded.price,
  price_note = excluded.price_note,
  badge = excluded.badge,
  featured = excluded.featured,
  sort_order = excluded.sort_order,
  description = excluded.description,
  status = excluded.status,
  updated_at = excluded.updated_at;`,
  );

  productStatements.push(
    `DELETE FROM product_spec_items WHERE product_slug = ${sqlValue(slug)};`,
  );
  productStatements.push(
    `DELETE FROM product_spec_groups WHERE product_slug = ${sqlValue(slug)};`,
  );
  productStatements.push(
    `DELETE FROM product_quick_specs WHERE product_slug = ${sqlValue(slug)};`,
  );
  productStatements.push(
    `DELETE FROM product_images WHERE product_slug = ${sqlValue(slug)};`,
  );
  productStatements.push(
    `DELETE FROM product_colors WHERE product_slug = ${sqlValue(slug)};`,
  );
  productStatements.push(
    `DELETE FROM product_offers WHERE product_slug = ${sqlValue(slug)};`,
  );
  productStatements.push(
    `DELETE FROM product_highlights WHERE product_slug = ${sqlValue(slug)};`,
  );

  quickSpecs.forEach((item, specIndex) => {
    productStatements.push(
      `INSERT INTO product_quick_specs (product_slug, sort_order, label, value)
VALUES (${sqlList([slug, specIndex, item.label || "", item.value || ""])});`,
    );
  });

  specs.forEach((group, groupIndex) => {
    productStatements.push(
      `INSERT INTO product_spec_groups (product_slug, group_index, group_name)
VALUES (${sqlList([slug, groupIndex, group.group || ""])});`,
    );
    const items = Array.isArray(group.items) ? group.items : [];
    items.forEach((item, itemIndex) => {
      productStatements.push(
        `INSERT INTO product_spec_items (product_slug, group_index, item_index, label, value)
VALUES (${sqlList([
          slug,
          groupIndex,
          itemIndex,
          item.label || "",
          item.value || "",
        ])});`,
      );
    });
  });

  images.forEach((image, imageIndex) => {
    const url = typeof image === "string" ? image : image?.url || "";
    const alt = typeof image === "string" ? "" : image?.alt || "";
    productStatements.push(
      `INSERT INTO product_images (product_slug, sort_order, url, alt)
VALUES (${sqlList([slug, imageIndex, url, alt])});`,
    );
  });

  colors.forEach((color, colorIndex) => {
    productStatements.push(
      `INSERT INTO product_colors (product_slug, sort_order, name, hex, image)
VALUES (${sqlList([
        slug,
        colorIndex,
        color.name || "",
        color.hex || "",
        color.image || "",
      ])});`,
    );
  });

  offers.forEach((offer, offerIndex) => {
    productStatements.push(
      `INSERT INTO product_offers (product_slug, sort_order, title, description, valid_until)
VALUES (${sqlList([
        slug,
        offerIndex,
        offer.title || "",
        offer.description || "",
        offer.validUntil || offer.valid_until || "",
      ])});`,
    );
  });

  highlights.forEach((highlight, highlightIndex) => {
    productStatements.push(
      `INSERT INTO product_highlights (product_slug, sort_order, title, text)
VALUES (${sqlList([
        slug,
        highlightIndex,
        highlight.title || "",
        highlight.text || "",
      ])});`,
    );
  });
});

writeSql(
  "02-products.sql",
  `Products (${products.length})`,
  productStatements,
);

/* ------------------------------------------------------------------ */
/* Sale programs                                                       */
/* ------------------------------------------------------------------ */

const programStatements = [];

salePrograms.forEach((program) => {
  const productId = program.productId;
  const items = Array.isArray(program.items) ? program.items : [];
  const details = Array.isArray(program.details) ? program.details : [];

  programStatements.push(
    `INSERT INTO sale_programs (product_id, enabled, percent_discount, flat_discount, updated_at)
VALUES (${sqlList([
      productId,
      program.enabled ? 1 : 0,
      Number(program.percentDiscount) || 0,
      Number(program.flatDiscount) || 0,
      seededAt,
    ])})
ON CONFLICT(product_id) DO UPDATE SET
  enabled = excluded.enabled,
  percent_discount = excluded.percent_discount,
  flat_discount = excluded.flat_discount,
  updated_at = excluded.updated_at;`,
  );

  programStatements.push(
    `DELETE FROM sale_program_items WHERE product_id = ${sqlValue(productId)};`,
  );
  programStatements.push(
    `DELETE FROM sale_program_details WHERE product_id = ${sqlValue(productId)};`,
  );

  items.forEach((item, index) => {
    programStatements.push(
      `INSERT INTO sale_program_items (product_id, sort_order, item_id, note)
VALUES (${sqlList([productId, index, item.itemId || item.id || "", item.note || ""])});`,
    );
  });

  details.forEach((detail, index) => {
    programStatements.push(
      `INSERT INTO sale_program_details (product_id, sort_order, title, text)
VALUES (${sqlList([productId, index, detail.title || "", detail.text || ""])});`,
    );
  });
});

writeSql(
  "03-sale-programs.sql",
  `Sale programs (${salePrograms.length})`,
  programStatements,
);

/* ------------------------------------------------------------------ */
/* Articles                                                            */
/* ------------------------------------------------------------------ */

const articleStatements = [];

articles.forEach((article) => {
  articleStatements.push(
    `INSERT INTO articles (
  slug, title, excerpt, category, cover_image, content_html, status, author,
  seo_title, seo_description, published_at, created_at, updated_at
) VALUES (${sqlList([
      article.slug,
      article.title,
      article.excerpt || "",
      article.category || "",
      article.coverImage || article.cover_image || "",
      article.contentHtml || article.content_html || "",
      article.status || "draft",
      article.author || "",
      article.seoTitle || article.seo_title || article.title || "",
      article.seoDescription || article.seo_description || article.excerpt || "",
      article.publishedAt || article.published_at || null,
      seededAt,
      seededAt,
    ])})
ON CONFLICT(slug) DO UPDATE SET
  title = excluded.title,
  excerpt = excluded.excerpt,
  category = excluded.category,
  cover_image = excluded.cover_image,
  content_html = excluded.content_html,
  status = excluded.status,
  author = excluded.author,
  seo_title = excluded.seo_title,
  seo_description = excluded.seo_description,
  published_at = excluded.published_at,
  updated_at = excluded.updated_at;`,
  );
});

writeSql(
  "04-articles.sql",
  `Articles (${articles.length})`,
  articleStatements,
);

console.log("\nDone. Run the files in numeric order against D1.");
